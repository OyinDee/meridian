/**
 * Builds a single migration file from two sources:
 *
 *   1. the DDL Prisma derives from `schema.prisma`, and
 *   2. the hand-written SQL in `prisma/sql/*.sql`, which expresses things Prisma
 *      cannot: deferred constraint triggers, append-only rules, partial indexes and
 *      the ledger proof functions.
 *
 * Both are concatenated into `prisma/migrations/<dir>/migration.sql`, which is what
 * `prisma migrate deploy` applies, in order, exactly once. Regenerating is safe:
 * the fragment files are the source of truth, and the build is deterministic, so a
 * reviewer can diff the generated SQL.
 *
 * Usage:
 *   node scripts/build-migration.mjs            # rebuild 0001_init
 *   node scripts/build-migration.mjs 0002_x     # name a new migration
 */
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const apiDir = path.join(root, 'apps', 'api');
const prismaDir = path.join(apiDir, 'prisma');
const sqlDir = path.join(prismaDir, 'sql');
const migrationsDir = path.join(prismaDir, 'migrations');

const migrationName = process.argv[2] ?? '0001_init';
const targetDir = path.join(migrationsDir, migrationName);

function readEnvFile(file) {
  try {
    const contents = readFileSync(file, 'utf8');
    const env = {};
    for (const line of contents.split(/\r?\n/)) {
      const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
      if (match) env[match[1]] = match[2].replace(/^["']|["']$/g, '');
    }
    return env;
  } catch {
    return {};
  }
}

const env = { ...readEnvFile(path.join(root, '.env')), ...process.env };
const prismaBin = path.join(apiDir, 'node_modules', '.bin', process.platform === 'win32' ? 'prisma.cmd' : 'prisma');

console.log('Generating DDL from schema.prisma ...');
const ddl = execFileSync(
  prismaBin,
  [
    'migrate',
    'diff',
    '--from-empty',
    '--to-schema-datamodel',
    path.join('prisma', 'schema.prisma'),
    '--script',
  ],
  { cwd: apiDir, env, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 128 * 1024 * 1024 },
);

const fragments = (await readdir(sqlDir)).filter((file) => file.endsWith('.sql')).sort();
if (fragments.length === 0) throw new Error(`No SQL fragments found in ${sqlDir}`);

const parts = [];
for (const fragment of fragments) {
  const body = await readFile(path.join(sqlDir, fragment), 'utf8');
  parts.push(`-- >>> ${fragment}\n\n${body.trimEnd()}\n`);
}

const header = [
  `-- Migration: ${migrationName}`,
  '--',
  '-- GENERATED by scripts/build-migration.mjs. Do not edit by hand: edit',
  '-- prisma/schema.prisma or prisma/sql/*.sql and rebuild.',
  '--',
  '-- Section 1 is Prisma DDL (tables, enums, foreign keys, indexes).',
  '-- Section 2 is hand-written SQL appended in filename order.',
  '',
  '-- ======================= Section 1: Prisma DDL =======================',
  '',
].join('\n');

const sql = `${header}${ddl.trimEnd()}\n\n-- ==================== Section 2: hand-written ========================\n\n${parts.join('\n')}`;

await mkdir(targetDir, { recursive: true });
await writeFile(path.join(targetDir, 'migration.sql'), sql, 'utf8');
await writeFile(
  path.join(migrationsDir, 'migration_lock.toml'),
  '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
  'utf8',
);

const lines = sql.split('\n').length;
console.log(`Wrote ${path.relative(root, path.join(targetDir, 'migration.sql'))} (${lines} lines, ${fragments.length} fragments)`);
